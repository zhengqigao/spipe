"""N4 -- the 2x2 photonic tensor core of ``examples/paper/ptc_hspice/test12.py``, with N1
substituted for its DACs.

What is the same and what is different
--------------------------------------
The **photonic netlist is byte-identical** to the one ``paper/ptc_hspice/test12.py`` writes: the same
``ps`` / ``mzi`` / ``pd`` differential-dot blocks, the same ``wdm1to2`` / ``splitter1to2`` /
``modm`` weight modulators, the same ``.mode`` / ``.freq`` / ``.source`` / ``.prob`` lines, the
same node names, the same numbers.  It is generated by the same code, reproduced here, and the
example checks it against ``paper/ptc_hspice/test12.sp`` character by character.
Optical results are therefore directly comparable with the published ones.

The **electronic netlist** replaces the sky130 BSIM4 DAC (``level=54``, two 7-bit interpolating
converters plus a CMOS switch per operand) with one Level-1 R-2R converter per operand, N1 in
``dac7_r2r_l1.sub``.  With ``--tia`` the detector front end is swapped as well, for N3's real
common-source TIA in place of the ideal 70 dB block of ``pd_level2``.  Nothing in the circuit
then needs a model more complicated than ``level=1``.

The point
---------
Everything in ``paper/ptc_hspice/`` is locked to a licensed simulator because of the foundry compact
models, not because of anything SPIPE does.  This is the same computation with the electronics
expressed in devices any SPICE-family engine can evaluate, so it is the version a native back
end can run.

Run it::

    python examples/derived/n4_ptc_dotproduct.py
    python examples/derived/n4_ptc_dotproduct.py --tia      # also swap in N3
"""

